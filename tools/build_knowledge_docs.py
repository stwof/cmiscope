"""Generate knowledge/SOURCES.md and knowledge/links.json from the graph data.

Keeping the published link manifest derived from data/knowledge_graph.json
means a new source can never silently lose its canonical URL. Run after
`python tools/build_kg.py`:

    python tools/build_knowledge_docs.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GRAPH = ROOT / "data" / "knowledge_graph.json"
OUT_DIR = ROOT / "knowledge"
SPECS_DIR = OUT_DIR / "specs"

KIND_ORDER = [
    ("oif_ia", "OIF Implementation Agreements"),
    ("oif_page", "OIF official index"),
    ("ietf_draft", "IETF drafts"),
    ("msa", "MSA / industry specifications"),
    ("standard_index", "SFF / SNIA standards"),
    ("github_repo", "GitHub open-source projects"),
    ("github_api", "GitHub API snapshots"),
    ("vendor_guide", "Vendor engineering guides"),
    ("technical_article", "Technical articles"),
    ("news", "Industry news"),
    ("internal_dataset", "Internal demo data"),
]

# Canonical, stable download links that are also bundled as local copies.
BUNDLED = {
    "S-OIF-053": "knowledge/specs/OIF-CMIS-05.3.pdf",
    "S-OIF-054": "knowledge/specs/OIF-CMIS-05.4.pdf",
}


def esc(value: str) -> str:
    return str(value or "").replace("|", "\\|").strip()


def build_links(sources: list[dict]) -> dict:
    return {
        "description": "Canonical links for every CMIS knowledge-graph source. "
                       "Bundled PDF copies are listed under bundled_copy.",
        "generated_from": "data/knowledge_graph.json",
        "count": len(sources),
        "sources": [
            {
                "source_id": s["source_id"],
                "title": s.get("title", ""),
                "kind": s.get("kind", ""),
                "url": s.get("url", ""),
                "publisher": s.get("publisher", ""),
                "license": s.get("license", ""),
                "retrieved_at": s.get("retrieved_at", ""),
                "bundled_copy": BUNDLED.get(s["source_id"]),
            }
            for s in sources
        ],
    }


def build_sources_md(sources: list[dict]) -> str:
    lines = [
        "# CMIS Knowledge Graph - Source Links",
        "",
        "Generated by `python tools/build_knowledge_docs.py` from "
        "`data/knowledge_graph.json`. Do not edit by hand.",
        "",
        "Every entity and relation in the graph carries `source_ids` that point "
        "to one of the entries below. `confidence` records how directly the "
        "claim was verified; see `CMIS_KNOWLEDGE_GRAPH.md`.",
        "",
        "Bundled PDF copies for offline use live in "
        "[`specs/`](specs/README.md); the canonical OIF URLs are always the "
        "authoritative version.",
        "",
        f"**Total: {len(sources)} sources.**",
        "",
    ]
    by_kind: dict[str, list[dict]] = {}
    for s in sources:
        by_kind.setdefault(s.get("kind", "other"), []).append(s)
    known = {k for k, _ in KIND_ORDER}
    groups = [(k, label) for k, label in KIND_ORDER if k in by_kind]
    groups += [(k, k) for k in sorted(by_kind) if k not in known]

    for kind, label in groups:
        lines += [f"## {label}", "",
                  "| ID | Title | Publisher | License | Link |",
                  "| --- | --- | --- | --- | --- |"]
        for s in by_kind[kind]:
            bundled = BUNDLED.get(s["source_id"])
            link = f"[canonical]({s.get('url', '')})"
            if bundled:
                # SOURCES.md lives in knowledge/, so strip the leading knowledge/
                local = bundled.split("/", 1)[1]
                link += f" · [bundled copy]({local})"
            lines.append(
                f"| `{esc(s['source_id'])}` | {esc(s.get('title',''))} | "
                f"{esc(s.get('publisher',''))} | {esc(s.get('license',''))} | {link} |"
            )
        lines.append("")
    lines += [
        "---",
        "",
        "## Refreshing",
        "",
        "```bash",
        "python tools/build_kg.py              # rebuild the graph",
        "python tools/build_knowledge_docs.py  # rebuild this file and links.json",
        "python tools/fetch_specs.py           # refresh the bundled PDF copies",
        "```",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    data = json.loads(GRAPH.read_text(encoding="utf-8"))
    sources = data["sources"]
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "links.json").write_bytes(
        (json.dumps(build_links(sources), ensure_ascii=False, indent=2) + "\n").encode("utf-8"))
    (OUT_DIR / "SOURCES.md").write_bytes(
        build_sources_md(sources).encode("utf-8"))
    print(f"wrote knowledge/SOURCES.md and knowledge/links.json | sources={len(sources)}")


if __name__ == "__main__":
    main()
