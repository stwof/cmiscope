"""Compile the curated Chinese -> English data dictionary into a static asset.

`data/i18n_data_en.json` is the source of truth: it maps every Chinese string
that the API can return (knowledge graph, source catalogue and generated seed
data) to its English wording.  This script validates coverage and emits
``cmis_service/static/js/data_en.js`` so the browser can localize data records
without changing any API response shape.

Usage: python tools/build_i18n_data.py [--check]
"""

from __future__ import annotations

import argparse
import ast
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAP = ROOT / "data" / "i18n_data_en.json"
OUT = ROOT / "cmis_service" / "static" / "js" / "data_en.js"
ZH = re.compile(r"[\u3400-\u9fff]")

DATA_FILES = (
    ROOT / "data" / "knowledge_graph.json",
    ROOT / "data" / "seed.json",
    ROOT / "knowledge" / "links.json",
)
SOURCE_FILES = (
    ROOT / "cmis_service" / "cmis_spec.py",
    ROOT / "tools" / "build_kg.py",
    ROOT / "tools" / "build_seed.py",
    ROOT / "tools" / "cmis_catalog.py",
    ROOT / "tools" / "build_knowledge_docs.py",
)


def collect(value: object, out: set[str]) -> None:
    if isinstance(value, dict):
        for item in value.values():
            collect(item, out)
    elif isinstance(value, list):
        for item in value:
            collect(item, out)
    elif isinstance(value, str) and ZH.search(value):
        out.add(value)


def source_strings() -> set[str]:
    out: set[str] = set()
    for path in DATA_FILES:
        if path.is_file():
            collect(json.loads(path.read_text(encoding="utf-8")), out)
    for path in SOURCE_FILES:
        if not path.is_file():
            continue
        tree = ast.parse(path.read_text(encoding="utf-8"))
        for node in ast.walk(tree):
            if isinstance(node, ast.Constant) and isinstance(node.value, str):
                if ZH.search(node.value):
                    out.add(node.value)
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="validate only; do not write")
    args = ap.parse_args()

    mapping = json.loads(MAP.read_text(encoding="utf-8"))
    problems: list[str] = []
    for zh, en in mapping.items():
        if not ZH.search(zh):
            problems.append(f"key is not Chinese: {zh!r}")
        if not isinstance(en, str) or not en.strip():
            problems.append(f"empty translation for {zh!r}")
        elif ZH.search(en):
            problems.append(f"Chinese leaked into English for {zh!r}: {en!r}")

    uncovered = sorted(s for s in source_strings() if s not in mapping)
    for text in uncovered:
        problems.append(f"untranslated data string: {text!r}")

    if problems:
        print(f"FAILED: {len(problems)} problem(s)")
        for line in problems[:30]:
            print("  -", line)
        return 1

    if not args.check:
        body = json.dumps(mapping, ensure_ascii=False, indent=2, sort_keys=True)
        OUT.write_text(
            "/* Generated by tools/build_i18n_data.py from data/i18n_data_en.json.\n"
            " * English wording for data records that are stored in Chinese.\n"
            " * Do not edit by hand. */\n"
            "window.CMIS_DATA_EN = " + body + ";\n",
            encoding="utf-8",
        )
        print(f"wrote {OUT.relative_to(ROOT)} | {len(mapping)} entries | "
              f"{OUT.stat().st_size:,} bytes | coverage OK")
    else:
        print(f"coverage OK | {len(mapping)} entries | 0 uncovered strings")
    return 0


if __name__ == "__main__":
    sys.exit(main())
