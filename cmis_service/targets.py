"""Editable target-device registry and per-request transport resolution.

Operators add or change a device by editing ``config/targets.json`` (or through
``PUT /api/targets``); no source changes are required. Credentials are never
stored in the registry: REST tokens are referenced by environment variable
name, and SSH relies on the operator's existing ssh-agent keys.

The registry is deliberately a plain JSON file so it can be edited in a
terminal, generated by configuration management, or checked into a private
inventory repository.
"""

from __future__ import annotations

import json
import logging
import os
import re
import tempfile
from dataclasses import replace
from pathlib import Path
from typing import Any

from .config import Settings

log = logging.getLogger("cmis.targets")

ACCESS_MODES = ("mirror", "ssh-i2c", "rest-api")
DEVICE_ID_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$")
REGISTRY_VERSION = 1

# Field -> description, used by the dashboard to render an editable form.
# ``modes`` lists the modes in which the field is visible / submittable. The
# two production transports are strictly mutually exclusive: a target must
# carry fields of its selected mode only, never both sets.
ALL_MODES = "mirror,ssh-i2c,rest-api"
CONNECTED_MODES = "ssh-i2c,rest-api"

TARGET_FIELDS: dict[str, dict[str, str]] = {
    "device_id": {"type": "text", "required": "true", "label": "Device ID", "modes": ALL_MODES},
    "name": {"type": "text", "label": "Display name", "modes": ALL_MODES},
    "enabled": {"type": "bool", "label": "Enabled", "modes": ALL_MODES},
    "access_mode": {"type": "enum", "label": "Access mode",
                    "values": ALL_MODES, "modes": ALL_MODES},
    "host": {"type": "text", "label": "IP / hostname", "modes": CONNECTED_MODES},
    "port": {"type": "int", "label": "Port", "modes": CONNECTED_MODES},
    "ssh_user": {"type": "text", "label": "SSH user", "modes": "ssh-i2c"},
    "i2c_bus": {"type": "text", "label": "I2C bus", "modes": "ssh-i2c"},
    "i2c_addr": {"type": "text", "label": "I2C address", "modes": "ssh-i2c"},
    "rest_scheme": {"type": "enum", "label": "REST scheme",
                    "values": "https,http", "modes": "rest-api"},
    "rest_base_path": {"type": "text", "label": "REST base path", "modes": "rest-api"},
    "token_env": {"type": "text", "label": "Token env var name", "modes": "rest-api"},
    "module_ids": {"type": "list", "label": "Module IDs", "modes": ALL_MODES},
    "notes": {"type": "text", "label": "Notes", "modes": ALL_MODES},
}

# Mode-specific keys. Anything belonging to an unselected mode is rejected on
# submission and never stored or returned for that target.
MODE_FIELD_KEYS: dict[str, frozenset[str]] = {
    "mirror": frozenset(),
    "ssh-i2c": frozenset({"ssh_user", "i2c_bus", "i2c_addr"}),
    "rest-api": frozenset({"rest_scheme", "rest_base_path", "token_env"}),
}
_COMMON_KEYS = frozenset({"device_id", "name", "enabled", "access_mode", "host",
                          "port", "module_ids", "notes"})
_ALL_MODE_KEYS = frozenset().union(*MODE_FIELD_KEYS.values())

# Reject literal credentials so they can never land in a config file or repo.
SENSITIVE_KEYS = frozenset({
    "token", "password", "passwd", "secret", "api_key", "apikey",
    "private_key", "credential", "credentials", "auth",
})

_ALLOWED_KEYS = _COMMON_KEYS | _ALL_MODE_KEYS


class TargetError(Exception):
    """Raised when a submitted registry fails validation."""

    def __init__(self, message: str, errors: list[str] | None = None):
        super().__init__(message)
        self.message = message
        self.errors = errors or [message]


def empty_registry() -> dict:
    """Return a valid minimal registry."""
    return {"version": REGISTRY_VERSION, "active_target": "", "targets": []}


def _read_json(path: Path) -> dict:
    with path.open("r", encoding="utf-8") as fh:
        data = json.load(fh)
    if not isinstance(data, dict):
        raise ValueError("root must be a JSON object")
    return data


def load_registry(path: Path, example: Path | None = None) -> dict:
    """Load the registry, falling back to the shipped example and never raising.

    A malformed or partially written file degrades to the example registry so
    the dashboard stays available; the reason is logged, not returned to the
    caller (it may contain local paths).
    """
    candidates = [Path(path)]
    if example is not None:
        candidates.append(Path(example))
    for candidate in candidates:
        if not candidate.is_file():
            continue
        try:
            data = _read_json(candidate)
            cleaned, errors = validate_registry(data)
            if errors:
                log.warning("Target registry %s has invalid entries: %s",
                            candidate.name, "; ".join(errors[:5]))
            return cleaned
        except (OSError, ValueError, json.JSONDecodeError) as exc:
            log.warning("Cannot read target registry %s: %s", candidate.name, exc)
    return empty_registry()


def _clean_str(value: Any, default: str = "") -> str:
    if value is None:
        return default
    return str(value).strip()


def _clean_target(raw: Any, index: int, seen: set[str], errors: list[str]) -> dict | None:
    if not isinstance(raw, dict):
        errors.append(f"targets[{index}] must be an object")
        return None

    forbidden = sorted(k for k in raw if str(k).lower() in SENSITIVE_KEYS)
    if forbidden:
        errors.append(
            f"targets[{index}] contains literal credential fields ({', '.join(forbidden)}); "
            "use token_env to reference an environment variable instead"
        )
        return None

    device_id = _clean_str(raw.get("device_id"))
    if not DEVICE_ID_RE.fullmatch(device_id):
        errors.append(f"targets[{index}].device_id is missing or invalid: {device_id!r}")
        return None
    if device_id in seen:
        errors.append(f"duplicate device_id: {device_id}")
        return None
    seen.add(device_id)

    mode = _clean_str(raw.get("access_mode"), "mirror").lower()
    if mode not in ACCESS_MODES:
        errors.append(f"{device_id}: access_mode must be one of {', '.join(ACCESS_MODES)}")
        return None

    # Strict mutual exclusion: ssh+i2c and restful API must never be mixed in
    # one target. Keys of the unselected mode are neither accepted nor stored.
    inactive_keys = sorted(k for k in raw
                           if k in _ALL_MODE_KEYS and k not in MODE_FIELD_KEYS[mode])
    if inactive_keys:
        errors.append(
            f"{device_id}: fields of the unselected access mode are not allowed for "
            f"{mode} ({', '.join(inactive_keys)}); submit only one transport's fields"
        )
        return None

    host = _clean_str(raw.get("host"))
    if mode in ("ssh-i2c", "rest-api") and not host:
        errors.append(f"{device_id}: host (IP / hostname) is required for {mode}")
        return None
    # Reject shell/URL metacharacters; host is used in an ssh argv and a URL.
    if host and not re.fullmatch(r"[A-Za-z0-9._:\-\[\]]+", host):
        errors.append(f"{device_id}: host contains unsafe characters")
        return None

    try:
        port = int(raw.get("port") or (22 if mode == "ssh-i2c" else 443))
        if mode == "mirror":
            port = int(raw.get("port") or 0)
    except (TypeError, ValueError):
        errors.append(f"{device_id}: port must be an integer")
        return None
    if port and not 1 <= port <= 65535:
        errors.append(f"{device_id}: port out of range 1-65535")
        return None

    scheme = "https"
    if mode == "rest-api":
        scheme = _clean_str(raw.get("rest_scheme"), "https").lower()
        if scheme not in ("http", "https"):
            errors.append(f"{device_id}: rest_scheme must be http or https")
            return None

    modules = raw.get("module_ids") or []
    if not isinstance(modules, list):
        errors.append(f"{device_id}: module_ids must be a list")
        return None

    enabled = raw.get("enabled", True)
    if isinstance(enabled, str):
        enabled = enabled.strip().lower() not in ("0", "false", "no", "off")
    else:
        enabled = bool(enabled)

    item = {
        "device_id": device_id,
        "name": _clean_str(raw.get("name")) or device_id,
        "enabled": enabled,
        "access_mode": mode,
        "host": host,
        "port": port,
        "module_ids": [_clean_str(m) for m in modules if _clean_str(m)][:32],
        "notes": _clean_str(raw.get("notes"))[:300],
    }
    # Only the selected mode's parameters appear in the stored / displayed
    # configuration; the other transport has no representation at all.
    if mode == "ssh-i2c":
        item.update({
            "ssh_user": _clean_str(raw.get("ssh_user"), "admin"),
            "i2c_bus": _clean_str(raw.get("i2c_bus"), "0"),
            "i2c_addr": _clean_str(raw.get("i2c_addr"), "0x50"),
        })
    elif mode == "rest-api":
        item.update({
            "rest_scheme": scheme,
            "rest_base_path": _clean_str(raw.get("rest_base_path")),
            "token_env": _clean_str(raw.get("token_env"), "CMIS_REST_TOKEN"),
        })
    return item


def validate_registry(data: Any) -> tuple[dict, list[str]]:
    """Validate and normalize a registry; return (clean_registry, errors).

    Each target keeps only the fields of its selected access_mode; mixing
    ssh+i2c and restful API fields is an error, so such a target is dropped and
    a save is rejected. Unknown keys are ignored.
    """
    errors: list[str] = []
    if not isinstance(data, dict):
        return empty_registry(), ["registry root must be a JSON object"]

    raw_targets = data.get("targets", [])
    if not isinstance(raw_targets, list):
        return empty_registry(), ["targets must be a list"]

    cleaned: list[dict] = []
    seen: set[str] = set()
    for i, raw in enumerate(raw_targets):
        item = _clean_target(raw, i, seen, errors)
        if item is not None:
            cleaned.append(item)

    active = _clean_str(data.get("active_target"))
    if active and active not in seen:
        errors.append(f"active_target {active!r} does not match any target; ignored")
        active = ""
    if not active:
        active = next((t["device_id"] for t in cleaned if t["enabled"]), "")

    return {"version": REGISTRY_VERSION, "active_target": active, "targets": cleaned}, errors


def save_registry(path: Path, data: Any) -> dict:
    """Validate then atomically write the registry as UTF-8 with LF endings."""
    cleaned, errors = validate_registry(data)
    if errors:
        raise TargetError("Target configuration validation failed", errors)

    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    payload = (json.dumps(cleaned, ensure_ascii=False, indent=2) + "\n").encode("utf-8")
    fd, tmp_name = tempfile.mkstemp(prefix=".targets-", suffix=".json", dir=str(target.parent))
    try:
        with os.fdopen(fd, "wb") as fh:
            fh.write(payload)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp_name, target)
    except OSError:
        try:
            os.unlink(tmp_name)
        except OSError:
            pass
        raise
    log.info("Target registry saved | path=%s targets=%d", target.name, len(cleaned["targets"]))
    return cleaned


def find_target(registry: dict, device_id: str | None) -> dict | None:
    """Return the named target, or the active target when device_id is omitted."""
    targets = registry.get("targets", [])
    if device_id:
        return next((t for t in targets if t.get("device_id") == device_id), None)
    active = registry.get("active_target", "")
    return next((t for t in targets if t.get("device_id") == active), None)


def public_target(target: dict | None) -> dict:
    """Return a browser-safe view; never includes token values.

    Only the selected mode's fields are exposed. A non-REST target has no
    token/TLS fields at all, so the browser never renders the other transport.
    """
    if not target:
        return {}
    view = dict(target)
    if view.get("access_mode") == "rest-api":
        env_name = str(view.get("token_env") or "")
        view["token_present"] = bool(os.environ.get(env_name)) if env_name else False
        view["token_env"] = env_name  # name only, never the value
    return view


def resolve_settings(base: Settings, target: dict | None) -> Settings:
    """Overlay a target's connection parameters onto the global settings.

    Returns a new frozen Settings instance so the adapters stay stateless and
    the global configuration is never mutated.
    """
    if not target or not target.get("enabled", True):
        return base
    mode = target.get("access_mode") or base.access_mode
    if mode not in ACCESS_MODES:
        return base
    # Disable both transports first, then enable exactly one. This guarantees
    # that an unselected mode can never take effect through inherited global
    # settings (for example a rest_base_url left in config.ini).
    overrides: dict[str, Any] = {
        "access_mode": mode,
        "ssh_host": "",
        "rest_base_url": "",
        "rest_token_env": "",
    }

    host = str(target.get("host") or "")
    port = int(target.get("port") or 0)
    if mode == "ssh-i2c":
        overrides.update({
            "ssh_host": host,
            "ssh_user": str(target.get("ssh_user") or base.ssh_user),
            "ssh_port": port or base.ssh_port,
            "i2c_bus": str(target.get("i2c_bus") or base.i2c_bus),
            "i2c_addr": str(target.get("i2c_addr") or base.i2c_addr),
        })
    elif mode == "rest-api":
        scheme = str(target.get("rest_scheme") or "https")
        base_path = str(target.get("rest_base_path") or "").strip().rstrip("/")
        url = f"{scheme}://{host}"
        if port and not ((scheme == "https" and port == 443) or (scheme == "http" and port == 80)):
            url += f":{port}"
        url += base_path
        overrides.update({
            "rest_base_url": url,
            "rest_token_env": str(target.get("token_env") or base.rest_token_env),
        })
    return replace(base, **overrides)
